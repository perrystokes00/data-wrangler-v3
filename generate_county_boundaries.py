def generate(out_path: str) -> int:
    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)

    records = []
    for name, state, fips, coords in COUNTIES:
        records.append({
            "COUNTY":    name,
            "STATE":     state,
            "FIPS":      fips,
            "LABEL":     f"{name}, {state}",
            "geometry":  Polygon(coords),
        })

    gdf = gpd.GeoDataFrame(records, crs="EPSG:4326")
    gdf.to_file(str(out))
    print(f"Written: {out}  ({len(gdf)} counties)")
    return len(gdf)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=r"spatial\Permian_Basin_Counties.shp",
                    help="Output shapefile path")
    args = ap.parse_args()
    n = generate(args.out)
    print(f"Done — {n} counties")


if __name__ == "__main__":
    main()
